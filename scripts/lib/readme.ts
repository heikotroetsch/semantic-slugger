function defaultOf(key: Key, given: string | undefined): string {
  if (given !== undefined) return given
  const v = (DEFAULTS as Record<string, unknown>)[key]
  if (v === undefined) return '-'
  return `\`${JSON.stringify(v).replaceAll('"', "'").replaceAll(',', ', ')}\``
}

export function configTable(): string {
  const rows = CONFIG_DOCS.map((d) => `| \`${d.key}\` | ${d.type} | ${defaultOf(d.key, d.default)} | ${d.effect} |`)
  return ['| Option | Type | Default | Effect |', '| --- | --- | --- | --- |', ...rows].join('\n')
}

function replaceBlock(readme: string, name: string, body: string): string {
  const [start, end] = marker(name)
  const a = readme.indexOf(start)
  const b = readme.indexOf(end)
  if (a < 0 || b < a) throw new Error(`README.md: markers of ${name} not found`)
  return `${readme.slice(0, a + start.length)}\n\n${body}\n\n${readme.slice(b)}`
}

/** The README with all generated tables up to date. Throws when a marker is missing. */
export function updateReadme(readme: string): string {
  const withExamples = replaceBlock(readme, 'examples-table', examplesTable())
  return replaceBlock(replaceBlock(withExamples, 'languages-table', languagesTable()), 'config-table', configTable())
}
